#!/usr/bin/env bash
#
# tools/agent-shims.sh — generate the per-harness instruction files from agent/.
#
# Almagest keeps its rules in exactly one place: agent/rules/*.md. Every harness
# wants them somewhere else, under a different name, with different frontmatter.
# This script writes those somewhere-elses as POINTERS, never as copies. A copied
# rule drifts the first time someone edits one of the two; a pointer cannot.
#
#   tools/agent-shims.sh generate   write/refresh every shim
#   tools/agent-shims.sh check      regenerate to a temp dir, diff, exit 1 on drift
#
# Everything it emits is derived from three sources:
#   agent/routing.md   → the "overview" and "routing" marker blocks
#   brain/rules-index.md → the "non-negotiables" marker block
#   agent/contract.md  → the "harness-table" and "adding-a-harness" blocks
#   this file          → per-harness framing and frontmatter
# Edit the source, then regenerate. Never edit a generated file.
#
# Output is deterministic: no dates, no hostnames, no ordering by filesystem.
# Running generate twice produces identical bytes. That is what makes `check`
# usable in CI.
#
# Dependencies: bash, awk, mkdir, diff, mktemp, rm. Nothing to install.

set -euo pipefail

# Byte semantics, so the marker matching below is not locale-dependent.
export LC_ALL=C

TOOLS_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_DIR="$(cd "$TOOLS_DIR/.." && pwd)"

ROUTING_SRC="$REPO_DIR/agent/routing.md"
AGENTS_SRC="$REPO_DIR/brain/rules-index.md"
CONTRACT_SRC="$REPO_DIR/agent/contract.md"

if [ -t 2 ] && [ -z "${NO_COLOR:-}" ]; then
    C_RED=$'\033[31m'; C_YEL=$'\033[33m'; C_GRN=$'\033[32m'
    C_DIM=$'\033[2m';  C_BLD=$'\033[1m';  C_OFF=$'\033[0m'
else
    C_RED=; C_YEL=; C_GRN=; C_DIM=; C_BLD=; C_OFF=
fi

die()  { printf '%s\n' "${C_RED}✗ $*${C_OFF}" >&2; exit 1; }
warn() { printf '%s\n' "${C_YEL}⚠ $*${C_OFF}" >&2; }
ok()   { printf '%s\n' "${C_GRN}✓ $*${C_OFF}" >&2; }
info() { printf '%s\n' "$*" >&2; }
dim()  { printf '%s\n' "${C_DIM}$*${C_OFF}" >&2; }

need_cmd() {
    command -v "$1" >/dev/null 2>&1 || die "required command not found on PATH: $1"
}

usage() {
    cat <<'USAGE'
Usage: tools/agent-shims.sh <generate|check>

  generate   Write every per-harness instruction file from agent/routing.md,
             brain/rules-index.md, and the templates in this script.
  check      Regenerate into a temp dir and diff against the working tree.
             Exit 1 if any shim is stale, missing, or hand-edited.

Sources of truth:
  agent/rules/read.md · agent/rules/ingest.md · agent/rules/wiki.md
  agent/routing.md    (overview + routing table blocks)
  brain/rules-index.md     (the non-negotiables)
USAGE
}

# The exact set of files this script owns. `check` diffs every one of them, so a
# shim deleted from the working tree is drift, not a silent pass.
SHIM_FILES="
CLAUDE.md
AGENTS.md
GEMINI.md
.github/copilot-instructions.md
brain/CLAUDE.md
brain/AGENTS.md
.claude/rules/brain-ingest.md
.claude/rules/brain-wiki.md
.cursor/rules/almagest-read.mdc
.cursor/rules/almagest-ingest.mdc
.cursor/rules/almagest-wiki.mdc
"

# Files this script does NOT own outright. They are hand-written, and carry one
# generated block between SHIM markers. `check` diffs them like any other shim,
# so an edit inside the block is drift; an edit outside it is just editing.
SPLICE_FILES="
docs/agent-harnesses.md
"

GEN_MARKER='<!-- GENERATED by tools/agent-shims.sh — do not edit. Edit agent/rules/*.md and regenerate. -->'

# ── source blocks ────────────────────────────────────────────────────────────

# Pull the text between <!-- SHIM:BEGIN name --> and <!-- SHIM:END name -->.
# Fails loudly on a missing or empty block: a shim built from a silently-empty
# block would look fine and say nothing, which is the worst outcome here.
extract_block() {
    local name="$1" file="$2" out
    [ -f "$file" ] || die "source file not found: ${file#"$REPO_DIR"/}"
    out="$(awk -v n="$name" '
        $0 == "<!-- SHIM:BEGIN " n " -->" { inblk = 1; next }
        $0 == "<!-- SHIM:END "   n " -->" { inblk = 0; found = 1; next }
        inblk { print }
        END { if (!found) exit 3 }
    ' "$file")" || die "marker block '$name' not found in ${file#"$REPO_DIR"/}"
    [ -n "$out" ] || die "marker block '$name' in ${file#"$REPO_DIR"/} is empty"
    printf '%s\n' "$out"
}

# ── per-harness framing ──────────────────────────────────────────────────────

NOTE_CLAUDE_CODE="$(cat <<'EOF'
## Loading on Claude Code

Path-scoped rules load on their own: `brain/raw/**` pulls in `.claude/rules/brain-ingest.md`, `brain/wiki/**` pulls in `.claude/rules/brain-wiki.md`, and `brain/CLAUDE.md` covers reads. Each is a pointer — open the `agent/rules/` file it names. `.mcp.json` is read automatically, so remote sources in `brain.config.yaml` → `sources.remote` need no extra setup.
EOF
)"

NOTE_WEAK="$(cat <<'EOF'
## Loading on this harness

There is no path-scoped rule loading here — this file is all you get. The routing table above is therefore the mechanism, not a backstop: open the named rule file yourself, in full, before the operation rather than after it. An agent that skips that step is running without the rules, not with a lighter version of them.
EOF
)"

# ── templates ────────────────────────────────────────────────────────────────

# Always-on file: project overview + the non-negotiables + routing table +
# one harness-specific section. Carried by every harness that loads exactly one
# instruction file per session.
always_on() {
    local title="$1" note="$2"
    printf '%s\n\n' "$GEN_MARKER"
    printf '# %s\n\n' "$title"
    printf '%s\n\n' "$OVERVIEW"
    cat <<'EOF'
## Non-negotiables

These hold across every operation, on every harness. Everything else is in the rule files named by the routing table below.

EOF
    printf '%s\n\n' "$NONNEG"
    cat <<'EOF'
## Rule routing

The rules live in `agent/rules/`. Each file opens with a "Load this when" line stating exactly which operations it governs. Read the file named below **before** the operation, not after.

EOF
    printf '%s\n\n' "$ROUTING"
    printf '%s\n\n' "$note"
    cat <<'EOF'
## Harness contract

`agent/contract.md` states what a harness must provide to run Almagest at all. Requirement 5 is a reviewer who merges: the agent commits to an `ingest/<source-slug>-<sha7>` branch and `main` moves only when a human merges a reviewed diff. Unattended ingest onto a branch is supported; an unattended merge to `main` is forbidden and there is no flag for it. Requirement 7 is Node 22+ for `tools/audit.mjs`, whose exit code gates the commit.
EOF
}

# Pointer file: names what it governs, when it applies, and where the real rule
# is. It must never restate a rule — that is the drift this script exists to
# prevent. Keep it under 25 lines.
pointer() {
    local frontmatter="$1" heading="$2" rule="$3" governs="$4" applies="$5"
    if [ -n "$frontmatter" ]; then
        printf '%s\n\n' "$frontmatter"
    fi
    printf '%s\n\n' "$GEN_MARKER"
    printf '# %s\n\n' "$heading"
    printf 'Governs: %s\n\n' "$governs"
    printf 'Applies when: %s\n\n' "$applies"
    printf '**Read `%s` in full before proceeding — it is the authoritative version.**\n' "$rule"
    printf 'This file is a pointer. The rules are deliberately not duplicated here: a copy drifts, a pointer cannot.\n\n'
    printf 'Read `brain.config.yaml` before any operation. Full routing table: `agent/routing.md`. Harness requirements: `agent/contract.md`.\n'
}

# ── writing ──────────────────────────────────────────────────────────────────

# macOS and Windows filesystems are case-insensitive: two paths differing only in
# case are one file, so a shim can silently destroy a hand-written neighbour.
# (This is why the rule index is brain/rules-index.md and not brain/agents.md —
# the latter IS brain/AGENTS.md on those filesystems.) Kept as a standing guard:
# a generator that eats a source file is worse than one that stops.
guard_case_collision() {
    local dst="$1" dir base other
    dir="$(dirname "$dst")"
    base="$(basename "$dst")"
    [ -d "$dir" ] || return 0
    other="$(ls -1 "$dir" 2>/dev/null \
        | awk -v b="$base" 'tolower($0) == tolower(b) && $0 != b { print; exit }')"
    [ -z "$other" ] || die "case collision: $dst would overwrite $dir/$other on a case-insensitive filesystem"
}

# splice_into <relative-path> <block-name> <body> — copy a hand-written file into
# $OUT_DIR with the named marker block replaced. Copying first is what lets
# `check` diff a partly-generated file with exactly the same code path as a fully
# generated one.
splice_into() {
    local rel="$1" name="$2" body="$3" src dst tmp out
    dst="$OUT_DIR/$rel"
    # Chain: a second block spliced into the same file must read the first
    # splice's output, not the working tree again — otherwise, under `check`,
    # the later splice silently discards the earlier one and stops verifying it.
    if [ -f "$dst" ] && [ "$dst" != "$REPO_DIR/$rel" ]; then src="$dst"
    else                                                    src="$REPO_DIR/$rel"; fi
    [ -f "$src" ] || die "splice target not found: $rel"
    mkdir -p "$(dirname "$dst")"
    tmp="$(mktemp -t almagest-splice.XXXXXX)"
    out="$(mktemp -t almagest-spliced.XXXXXX)"
    printf '%s\n' "$body" > "$tmp"
    # Never redirect straight onto $dst: on a `generate` run $dst IS $src, and
    # the shell truncates the target before awk opens it. Build aside, then move.
    awk -v n="$name" -v bodyfile="$tmp" '
        $0 == "<!-- SHIM:BEGIN " n " -->" {
            print
            while ((getline line < bodyfile) > 0) print line
            close(bodyfile)
            inblk = 1; found = 1; next
        }
        $0 == "<!-- SHIM:END " n " -->" { print; inblk = 0; next }
        inblk { next }
        { print }
        END { if (!found) exit 3 }
    ' "$src" > "$out" || { rm -f "$tmp" "$out"; die "marker block '$name' not found in $rel"; }
    mv "$out" "$dst"
    rm -f "$tmp"
}

# emit <relative-path>  — body on stdin, written under $OUT_DIR.
emit() {
    local dst="$OUT_DIR/$1"
    mkdir -p "$(dirname "$dst")"
    guard_case_collision "$dst"
    cat > "$dst"
}

generate_all() {
    OUT_DIR="$1"
    [ -n "$OUT_DIR" ] || die "generate_all called without an output directory"

    OVERVIEW="$(extract_block overview "$ROUTING_SRC")"
    ROUTING="$(extract_block routing "$ROUTING_SRC")"
    NONNEG="$(extract_block non-negotiables "$AGENTS_SRC")"

    # Always-on routing files. One template, four harnesses; they differ only in
    # the title and the loading note. Splitting them into hand-written files is
    # exactly how the two copies drift.
    always_on 'CLAUDE.md — Almagest' "$NOTE_CLAUDE_CODE" | emit 'CLAUDE.md'
    always_on 'AGENTS.md — Almagest' "$NOTE_WEAK"        | emit 'AGENTS.md'
    always_on 'GEMINI.md — Almagest' "$NOTE_WEAK"        | emit 'GEMINI.md'
    always_on 'Almagest — Copilot instructions' "$NOTE_WEAK" \
        | emit '.github/copilot-instructions.md'

    # Reader pointer, one per always-on filename. Path-scoped on Claude Code;
    # a nested AGENTS.md is read by the harnesses that support one, and ignored
    # harmlessly by those that do not — they already carry the routing table in
    # the root AGENTS.md.
    for reader_dst in brain/CLAUDE.md brain/AGENTS.md; do
        pointer '' 'Brain — Reader Instructions (pointer)' 'agent/rules/read.md' \
            'the query protocol and the citation format for answers' \
            'you are about to answer a question from `brain/wiki/` or `brain/index.md`, or write a citation' \
            | emit "$reader_dst"
    done

    # Claude Code path-scoped rules.
    pointer "$(printf -- '---\npaths:\n  - "brain/raw/**"\n---')" \
        'Brain — Ingest Rules (pointer)' 'agent/rules/ingest.md' \
        'ingest — `raw/` and remote sources into `wiki/`, fingerprinting, extracted sidecars, the manifest, the ingest branch' \
        'you are about to process anything in `brain/raw/`, or a source in `brain.config.yaml` → `sources.remote`' \
        | emit '.claude/rules/brain-ingest.md'
    pointer "$(printf -- '---\npaths:\n  - "brain/wiki/**"\n---')" \
        'Brain — Wiki Write Rules (pointer)' 'agent/rules/wiki.md' \
        'writing — the ingest branch and its blocking cases, contradictions, the page template, content tiers, the audit' \
        'you are about to create, edit, delete, or merge anything in `brain/wiki/`, or run an audit' \
        | emit '.claude/rules/brain-wiki.md'

    # Cursor path-scoped rules. Same three rule files, Cursor frontmatter.
    pointer "$(printf -- '---\ndescription: Almagest — query protocol and citation format\nglobs: brain/**\nalwaysApply: false\n---')" \
        'Brain — Reader Instructions (pointer)' 'agent/rules/read.md' \
        'the query protocol and the citation format for answers' \
        'you are about to answer a question from `brain/wiki/` or `brain/index.md`, or write a citation' \
        | emit '.cursor/rules/almagest-read.mdc'
    pointer "$(printf -- '---\ndescription: Almagest — ingest rules for brain/raw/\nglobs: brain/raw/**\nalwaysApply: false\n---')" \
        'Brain — Ingest Rules (pointer)' 'agent/rules/ingest.md' \
        'ingest — `raw/` and remote sources into `wiki/`, fingerprinting, extracted sidecars, the manifest, the ingest branch' \
        'you are about to process anything in `brain/raw/`, or a source in `brain.config.yaml` → `sources.remote`' \
        | emit '.cursor/rules/almagest-ingest.mdc'
    pointer "$(printf -- '---\ndescription: Almagest — write rules for brain/wiki/\nglobs: brain/wiki/**\nalwaysApply: false\n---')" \
        'Brain — Wiki Write Rules (pointer)' 'agent/rules/wiki.md' \
        'writing — the ingest branch and its blocking cases, contradictions, the page template, content tiers, the audit' \
        'you are about to create, edit, delete, or merge anything in `brain/wiki/`, or run an audit' \
        | emit '.cursor/rules/almagest-wiki.mdc'

    # The known-good harness table lives in agent/contract.md — the normative
    # document, and the one an agent reads. The docs page shows the same table
    # rather than keeping a second copy of it.
    splice_into 'docs/agent-harnesses.md' harness-table \
        "$(extract_block harness-table "$CONTRACT_SRC")"
    splice_into 'docs/agent-harnesses.md' adding-a-harness \
        "$(extract_block adding-a-harness "$CONTRACT_SRC")"
}

# Every rule file a shim points at must exist, or the shim sends the agent to a
# dead end and the rules silently stop applying.
check_rule_files() {
    local f
    for f in agent/rules/read.md agent/rules/ingest.md agent/rules/wiki.md agent/contract.md agent/routing.md; do
        [ -f "$REPO_DIR/$f" ] || die "shims point at a file that does not exist: $f"
    done
}

# ── subcommands ──────────────────────────────────────────────────────────────

cmd_generate() {
    check_rule_files
    generate_all "$REPO_DIR"
    local f n=0
    for f in $SHIM_FILES $SPLICE_FILES; do
        [ -f "$REPO_DIR/$f" ] || die "generate did not produce $f"
        n=$((n + 1))
        dim "  $f"
    done
    ok "$n shims generated from agent/routing.md, brain/rules-index.md, agent/rules/"
}

cmd_check() {
    check_rule_files
    local drift=0 missing=0 f
    # Not local: the EXIT trap fires after this function has returned, and under
    # `set -u` a local would be unbound by then.
    SHIM_TMP="$(mktemp -d -t almagest-shims.XXXXXX)"
    trap 'rm -rf "$SHIM_TMP"' EXIT
    generate_all "$SHIM_TMP"

    for f in $SHIM_FILES $SPLICE_FILES; do
        if [ ! -f "$REPO_DIR/$f" ]; then
            warn "missing: $f"
            missing=$((missing + 1))
            continue
        fi
        if ! diff -u "$REPO_DIR/$f" "$SHIM_TMP/$f" >/dev/null 2>&1; then
            warn "stale: $f"
            diff -u --label "$f (working tree)" --label "$f (regenerated)" \
                "$REPO_DIR/$f" "$SHIM_TMP/$f" >&2 || true
            drift=$((drift + 1))
        fi
    done

    if [ "$missing" -gt 0 ] || [ "$drift" -gt 0 ]; then
        info ""
        die "$drift stale, $missing missing — run: tools/agent-shims.sh generate"
    fi
    ok "all $(printf '%s\n' $SHIM_FILES $SPLICE_FILES | wc -l | tr -d ' ') shims are in sync"
}

# ── main ─────────────────────────────────────────────────────────────────────

need_cmd awk
need_cmd diff
need_cmd mktemp

case "${1:-}" in
    generate) cmd_generate ;;
    check)    cmd_check ;;
    -h|--help|help) usage ;;
    "")       usage >&2; die "no subcommand given" ;;
    *)        usage >&2; die "unknown subcommand: $1" ;;
esac
