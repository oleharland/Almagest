#!/usr/bin/env bash
# render_report.sh <run_dir> <mechanical_tsv> <judge_tsv> <judge_ran 0|1> <questions_tsv>
#
# Emits the run report on stdout. Never invents a number: any metric with no
# underlying data is printed as `not run` or `n/a`, never as a figure.
set -euo pipefail
export LC_ALL=C

RUN_DIR="$1"; MECH="$2"; JUDGE="$3"; JUDGE_RAN="$4"; QTSV="$5"

[ -f "$JUDGE" ] || JUDGE=/dev/null

awk -v judge_ran="$JUDGE_RAN" -v envfile="$RUN_DIR/run.env" \
    -v mech="$MECH" -v judge="$JUDGE" -v qtsv="$QTSV" '
function fmt(x, d) { return sprintf("%." d "f", x) }

function median(arr, n,   i, j, t, c) {
    for (i = 2; i <= n; i++) { t = arr[i]; j = i - 1
        while (j >= 1 && arr[j] > t) { arr[j+1] = arr[j]; j-- }
        arr[j+1] = t }
    if (n == 0) return ""
    if (n % 2) return arr[int(n/2) + 1]
    return (arr[n/2] + arr[n/2 + 1]) / 2
}

function pct(num, den) { if (den == 0) return "n/a"; return fmt(100 * num / den, 0) "%" }
function avg(sum, n, d) { if (n == 0) return "n/a"; return fmt(sum / n, d) }

BEGIN {
    FS = "\t"

    while ((getline line < envfile) > 0) {
        split(line, kv, "=")
        k = kv[1]; sub(/^[^=]*=/, "", line)
        env[k] = line
    }
    close(envfile)

    # question metadata
    while ((getline line < qtsv) > 0) {
        split(line, f, "\t")
        if (f[2] == "category") { qcat[f[1]] = f[3]; if (!(f[1] in qseen)) { qseen[f[1]] = 1; nq++; qorder[nq] = f[1] } }
        if (f[2] == "question") qtext[f[1]] = f[3]
    }
    close(qtsv)

    # mechanical values: M[arm,qid,metric]
    nmech = 0
    while ((getline line < mech) > 0) {
        split(line, f, "\t")
        if (f[1] == "arm") continue
        M[f[1], f[2], f[4]] = f[5]
        if (!((f[1] SUBSEP f[2]) in rowseen)) { rowseen[f[1], f[2]] = 1 }
        if (!(f[1] in armseen)) { armseen[f[1]] = 1; narm++; armorder[narm] = f[1] }
        nmech++
    }
    close(mech)

    njudge = 0
    if (judge != "/dev/null") {
        while ((getline line < judge) > 0) {
            split(line, f, "\t")
            if (f[1] == "arm") continue
            J[f[1], f[2], f[4]] = f[5]
            njudge++
        }
        close(judge)
    }

    # ── header ──────────────────────────────────────────────────────────────
    print "# Benchmark report — " env["run_id"]
    print ""
    print "Generated by `benchmarks/score.sh`. Every number below is computed from"
    print "the captured answers in this run directory. Nothing here is estimated."
    print ""
    print "## Run metadata"
    print ""
    print "| Field | Value |"
    print "|-------|-------|"
    printf("| Run id | `%s` |\n", env["run_id"])
    printf("| Date (UTC) | %s |\n", env["date_utc"])
    printf("| Answering model | `%s` |\n", env["model"])
    printf("| Arms | %s |\n", env["arms"])
    printf("| Questions | %s |\n", env["questions_count"])
    if ("scale" in env) {
        printf("| Corpus | %s document(s)%s |\n", env["corpus_documents"],
               (env["scale_generated"] + 0 > 0 \
                ? sprintf(" — %s real, **%s generated distractors**, seed `%s`", \
                          env["corpus_documents"] - env["scale_generated"], \
                          env["scale_generated"], env["scale_seed"]) \
                : ""))
    }
    printf("| Question set sha256 | `%s` |\n", substr(env["questions_sha256"], 1, 16) "…")
    printf("| Shared prompt sha256 | `%s` |\n", substr(env["shared_prompt_sha256"], 1, 16) "…")
    printf("| Driver | `%s` — %s |\n", (env["driver"] == "" ? "unknown" : env["driver"]),
                                       (env["driver_version"] == "" ? "version unknown" : env["driver_version"]))
    printf("| Repo commit | `%s`%s |\n", env["git_sha"], (env["git_dirty"] == "yes" ? " (working tree dirty)" : ""))
    printf("| Query-protocol drift | %s |\n", (env["protocol_drift"] == "1" ? "**yes — prompts/_shared.md is out of sync with agent/rules/read.md**" : "none"))
    if (env["driver"] == "fake")
        printf("| ⚠ Test double | `fake` — **stub, not the real CLI. These are not model answers.** |\n")
    print ""

    comparability()

    # ── mechanical aggregate ────────────────────────────────────────────────
    print "## Mechanically scored metrics"
    print ""
    print "Deterministic, free, reproducible. These are syntactic checks on the answer"
    print "text. **None of them can tell you whether an answer is true.**"
    print ""
    print "| Metric | " armhdr() " |"
    print "|--------|" armsep()

    row("Answers scored",                     "n_scored",        0)
    row("Unscorable (empty / failed)",        "n_unscorable",    0)
    row("Answers with no citation at all",    "no_citation",     0)
    row("Expected sources cited",             "src_cov",         0)
    row("Broken `[[wikilink]]` citations",    "broken_pages",    0)
    row("Fabricated document IDs",            "fab_docs",        0)
    row("Section-level citation precision",   "precision",       0)
    row("Ground-truth literal recall",        "recall",          0)
    row("`must_not_contain` hits (advisory)", "mnc",             0)
    row("Synthesis marker on synthesis Qs",   "syn_hit",         0)
    row("Synthesis marker on other Qs",       "syn_over",        0)
    row("Source value present (advisory)",    "poison_true",     0)
    row("Compiled-claim value present (advisory)", "poison_false", 0)
    row("Median latency",                     "lat_med",         0)
    row("Mean latency",                       "lat_mean",        0)
    row("Total cost (USD)",                   "cost_sum",        0)
    print ""
    print "The two advisory rows are literal-string checks on `poisoned_claim` and"
    print "`drift*` questions. An answer that reports the source value AND names the"
    print "conflicting one on the compiled page — the best possible answer — trips both."
    print "They narrow down which answers to read. **Neither is a propagation rate.** That is"
    print "`compiled_error`, below, and it needs a judge."
    print ""

    # ── judge aggregate ─────────────────────────────────────────────────────
    print "## Judge-scored metrics"
    print ""
    if (judge_ran != "1" || njudge == 0) {
        print "> **Not run.** The judge pass is opt-in because it costs tokens. Re-run with:"
        print "> "
        print "> ```bash"
        printf("> benchmarks/score.sh --run %s --judge\n", env["run_id"])
        print "> ```"
        print ""
        print "Format of the table this will produce — the tokens below are placeholders,"
        print "not results:"
        print ""
        print "| Metric | " armhdr() " |"
        print "|--------|" armsep()
        blankrow("Correctness (mean, 0–2)")
        blankrow("Fully correct")
        blankrow("Citation support (mean, 0–2)")
        blankrow("Unsourced claims (total)")
        blankrow("Confabulation rate on unanswerable Qs")
        blankrow("Correct declines (named the gap)")
        blankrow("Contradictions fully surfaced")
        blankrow("Synthesis correctly flagged")
        blankrow("Synthesis over-flagged elsewhere")
        blankrow("Compiled-error propagation rate")
        blankrow("Compiled errors caught and named")
        print ""
    } else {
        print "A model scored these against the ground truth, blind to which arm produced"
        print "each answer. They will move between runs. Treat them as an estimate with a"
        print "confidence interval you have not measured — see `benchmarks/README.md`."
        print ""
        print "| Metric | " armhdr() " |"
        print "|--------|" armsep()
        row("Correctness (mean, 0–2)",              "j_corr",      0)
        row("Fully correct (scored 2)",             "j_corr2",     0)
        row("Citation support (mean, 0–2)",         "j_cite",      0)
        row("Full citation support (scored 2)",     "j_cite2",     0)
        row("Unsourced claims (total)",             "j_unsourced", 0)
        row("Confabulation rate on unanswerable Qs","j_confab",    0)
        row("Correct declines (named the gap)",     "j_decline",   0)
        row("Contradictions fully surfaced",        "j_contra",    0)
        row("Synthesis correctly flagged",          "j_syn",       0)
        row("Synthesis over-flagged elsewhere",     "j_overflag",  0)
        row("Compiled-error propagation rate",      "j_prop",      0)
        row("Compiled errors caught and named",     "j_caught",    0)
        print ""
        print "**Compiled-error propagation rate** counts answers that asserted a claim a"
        print "compiled wiki page makes and the source documents contradict. An arm with no"
        print "wiki, or with a correct one, has nothing false in front of it and should sit"
        print "at zero — that is the control, not a result. Only an arm given a wiki that is"
        print "wrong or stale can put a number in this row that means anything."
        print ""
    }

    # ── per-question detail ─────────────────────────────────────────────────
    print "## Per-question detail"
    print ""
    print "| Q | Category | Arm | Cited | Broken links | Fabricated IDs | Recall | Latency (ms) | Judge: correct / citation / abstain / compiled |"
    print "|---|----------|-----|-------|--------------|----------------|--------|--------------|-----------------------------------------------|"
    for (qi = 1; qi <= nq; qi++) {
        q = qorder[qi]
        for (ai = 1; ai <= narm; ai++) {
            a = armorder[ai]
            if (!((a SUBSEP q) in rowseen)) continue
            if (M[a, q, "status"] == "unscorable") {
                printf("| `%s` | %s | %s | — | — | — | — | — | unscorable |\n", q, qcat[q], a)
                continue
            }
            je = ((a SUBSEP q SUBSEP "judge_compiled_error") in J) ? J[a, q, "judge_compiled_error"] : "—"
            et = M[a, q, "expected_sources_total"] + 0
            ec = M[a, q, "expected_sources_cited"] + 0
            mt = M[a, q, "must_contain_total"] + 0
            mh = M[a, q, "must_contain_hits"] + 0
            jc = ((a SUBSEP q SUBSEP "judge_correctness") in J) ? J[a, q, "judge_correctness"] : "—"
            js = ((a SUBSEP q SUBSEP "judge_citation_support") in J) ? J[a, q, "judge_citation_support"] : "—"
            ja = ((a SUBSEP q SUBSEP "judge_abstention") in J) ? J[a, q, "judge_abstention"] : "—"
            printf("| `%s` | %s | %s | %s | %s | %s | %s | %s | %s / %s / %s / %s |\n",
                   q, qcat[q], a,
                   (et > 0 ? ec "/" et : "n/a"),
                   M[a, q, "cited_pages_broken"] + 0,
                   M[a, q, "fabricated_doc_ids"] + 0,
                   (mt > 0 ? mh "/" mt : "n/a"),
                   (M[a, q, "latency_ms"] == "" ? "—" : M[a, q, "latency_ms"]),
                   jc, js, ja, je)
        }
    }
    print ""

    # ── flags ───────────────────────────────────────────────────────────────
    print "## Flags"
    print ""
    nflag = 0
    for (ai = 1; ai <= narm; ai++) {
        a = armorder[ai]
        for (qi = 1; qi <= nq; qi++) {
            q = qorder[qi]
            if (!((a SUBSEP q) in rowseen)) continue
            if (M[a, q, "status"] == "unscorable") { printf("- `%s`/`%s` — no answer captured. Excluded from every aggregate above.\n", a, q); nflag++ }
            if ((M[a, q, "fabricated_doc_ids"] + 0) > 0) { printf("- `%s`/`%s` — cited document id(s) that do not exist in the corpus: %s\n", a, q, M[a, q, "fabricated_doc_id_list"]); nflag++ }
            if ((M[a, q, "cited_pages_broken"] + 0) > 0) { printf("- `%s`/`%s` — cited wiki page(s) that do not exist: %s\n", a, q, M[a, q, "broken_page_slugs"]); nflag++ }
            if ((M[a, q, "must_not_contain_hits"] + 0) > 0) { printf("- `%s`/`%s` — matched a `must_not_contain` string. Advisory: read the answer before concluding anything.\n", a, q); nflag++ }
        }
    }
    if (nflag == 0) print "None."
    print ""
    print "---"
    print ""
    print "Raw answers, per-call metadata, and judge verdicts are in this directory."
    print "Read the answers before quoting any number from this report."
}

# ── comparability ────────────────────────────────────────────────────────────
# A capability the driver could not enforce is a fact about what these numbers
# mean, so it is stated here rather than left in run.env for someone to find.
function comparability(   keys, meaning, i, n, k, v, nbad, have) {
    n = split("tool_restriction budget_cap structured_output cost_reporting session_isolation sandbox", keys, " ")
    meaning["tool_restriction"]  = "the arms were not confined to the read-only tool allowlist. Nothing stopped an arm from reaching material the other could not see, so the one variable this design isolates was not isolated. **This run is not comparable to one where the restriction held.**"
    meaning["budget_cap"]        = "per-call spend was not capped. `--budget-usd` was advisory; the cost figures are what happened, not what was permitted."
    meaning["structured_output"] = "the driver could not hold the judge to `lib/judge-schema.json`. Any judge metric present came from unvalidated output — check `scores-judge.tsv` before quoting one."
    meaning["cost_reporting"]    = "the driver reports no per-call cost. Cost rows read `n/a`, which means unknown, not zero. Latency is still real."
    meaning["session_isolation"] = "state may have carried between calls. The answers are not independent samples and question order may have mattered."
    meaning["sandbox"]           = "the arms ran without a read-only mode. The arena is a throwaway copy, so the blast radius was still bounded — but nothing enforced it."

    print "## Comparability"
    print ""

    # Corpus size is the first thing that has to match, because it is the axis
    # this benchmark is least able to hide. At five documents an agent reads the
    # whole corpus and retrieval is not a constraint at all; at 500 it is the
    # constraint. A number from one tier says nothing about another.
    if (("scale" in env) && (env["scale_generated"] + 0) > 0) {
        printf("**Scaled corpus (`--scale %s`, seed `%s`).** %s of the %s documents are\n",
               env["scale"], env["scale_seed"], env["scale_generated"], env["corpus_documents"])
        print "generated distractors. They answer nothing, and they are shallower and more"
        print "uniform than real material would be, so this measures **retrieval pressure**"
        print "and not domain breadth — a weaker instrument than the same number of"
        print "genuinely distinct documents. Compare this run only against runs at the same"
        print "`--scale` AND the same `--scale-seed`; both are in `run.env`."
        print ""
    } else if ("scale" in env) {
        print "**Corpus: the five real sources.** Small enough that an agent can read all of"
        print "it, so retrieval is not yet a constraint and nothing here separates the"
        print "summarisation benefit of a compiled wiki from its retrieval benefit. Run at"
        print "`--scale 50` and `--scale 500` before claiming the second one exists."
        print ""
    }

    if ("arms" in env && index(" " env["arms"] " ", " poisoned ") == 0 \
        && index(" " env["arms"] " ", " drift ") == 0) {
        print "**No arm was given a defective wiki.** Neither `poisoned` nor `drift` ran, so"
        print "the compiled-error propagation rate has no arm that could produce a non-zero"
        print "value and this run says nothing about it."
        print ""
    }

    have = 0
    for (i = 1; i <= n; i++) if (("cap_" keys[i]) in env) have = 1
    if (!have) {
        print "Driver capabilities were not recorded for this run — it predates"
        print "`harness_version=2`. What the driver did and did not enforce is unknown,"
        print "so nothing here can be lined up against a run that records it."
        print ""
        return
    }

    nbad = 0
    for (i = 1; i <= n; i++) {
        k = keys[i]
        v = env["cap_" k]
        if (v != "no") continue
        if (nbad == 0) {
            printf("Driver `%s` could not enforce everything this benchmark asks for. Each\n", env["driver"])
            print "line below changes what the numbers above mean:"
            print ""
        }
        nbad++
        printf("- **`%s` = no** — %s\n", k, meaning[k])
    }

    if (nbad == 0) {
        printf("Driver `%s` enforced every capability the harness asks for. This run is\n", env["driver"])
        print "comparable to any other run whose `cap_*` lines are also all `yes`."
    } else {
        print ""
        print "Compare these numbers only against a run whose `cap_*` lines match. They are"
        print "all in `run.env`."
    }
    print ""
}

# ── aggregate helpers ────────────────────────────────────────────────────────
function armhdr(   i, s) { s = ""; for (i = 1; i <= narm; i++) s = s (i > 1 ? " | " : "") armorder[i]; return s }
function armsep(   i, s) { s = ""; for (i = 1; i <= narm; i++) s = s "----------|"; return s }

function row(label, key,   i, s) {
    s = "| " label " |"
    for (i = 1; i <= narm; i++) s = s " " cell(armorder[i], key) " |"
    print s
}

# A row of em-dashes, one cell per arm. Used only for the not-run judge table:
# it must show the SHAPE of the table without ever showing a number, and the
# shape depends on how many arms this run had.
function blankrow(label,   i, s) {
    s = "| " label " |"
    for (i = 1; i <= narm; i++) s = s " — |"
    print s
}

function cell(a, key,   qi, q, n, hit, sum, tot, den, nlat, v, unscorable, lats) {
    n = 0; hit = 0; sum = 0; tot = 0; den = 0; nlat = 0
    delete lats
    for (qi = 1; qi <= nq; qi++) {
        q = qorder[qi]
        if (!((a SUBSEP q) in rowseen)) continue
        unscorable = (M[a, q, "status"] == "unscorable")

        if (key == "n_scored")    { if (!unscorable) n++; continue }
        if (key == "n_unscorable"){ if (unscorable) n++; continue }
        if (unscorable) continue
        n++

        if (key == "no_citation")   { if ((M[a,q,"has_citation"]+0) == 0) hit++ }
        else if (key == "src_cov")  { sum += M[a,q,"expected_sources_cited"]+0; tot += M[a,q,"expected_sources_total"]+0 }
        else if (key == "broken_pages") { sum += M[a,q,"cited_pages_broken"]+0 }
        else if (key == "fab_docs")     { sum += M[a,q,"fabricated_doc_ids"]+0 }
        else if (key == "precision")    { if ((M[a,q,"section_precision"]+0) == 1) hit++ }
        else if (key == "recall")       { sum += M[a,q,"must_contain_hits"]+0; tot += M[a,q,"must_contain_total"]+0 }
        else if (key == "mnc")          { sum += M[a,q,"must_not_contain_hits"]+0 }
        else if (key == "syn_hit")      { if (qcat[q] == "synthesis") { den++; if ((M[a,q,"synthesis_marker"]+0) == 1) hit++ } }
        else if (key == "syn_over")     { if (qcat[q] != "synthesis") { den++; if ((M[a,q,"synthesis_marker"]+0) == 1) hit++ } }
        else if (key == "poison_true")  { if ((a SUBSEP q SUBSEP "poison_true_present") in M)  { den++; if ((M[a,q,"poison_true_present"]+0)  == 1) hit++ } }
        else if (key == "poison_false") { if ((a SUBSEP q SUBSEP "poison_false_present") in M) { den++; if ((M[a,q,"poison_false_present"]+0) == 1) hit++ } }
        else if (key == "lat_med" || key == "lat_mean") {
            v = M[a,q,"latency_ms"]; if (v != "") { nlat++; lats[nlat] = v + 0; sum += v + 0 } }
        else if (key == "cost_sum") { v = M[a,q,"cost_usd"]; if (v != "") sum += v + 0 }
        else if (substr(key, 1, 2) == "j_") { jaccum(a, q, key) }
    }

    if (key == "n_scored" || key == "n_unscorable") return n ""
    if (n == 0) return "n/a"
    if (key == "no_citation")   return hit " / " n
    if (key == "src_cov")       return (tot == 0 ? "n/a" : sum " / " tot "  (" pct(sum, tot) ")")
    if (key == "broken_pages")  return sum ""
    if (key == "fab_docs")      return sum ""
    if (key == "precision")     return hit " / " n "  (" pct(hit, n) ")"
    if (key == "recall")        return (tot == 0 ? "n/a" : sum " / " tot "  (" pct(sum, tot) ")")
    if (key == "mnc")           return sum ""
    if (key == "syn_hit" || key == "syn_over") return (den == 0 ? "n/a" : hit " / " den)
    if (key == "poison_true" || key == "poison_false") return (den == 0 ? "n/a" : hit " / " den "  (" pct(hit, den) ")")
    if (key == "lat_med")       return (nlat == 0 ? "n/a" : fmt(median(lats, nlat), 0))
    if (key == "lat_mean")      return (nlat == 0 ? "n/a" : fmt(sum / nlat, 0))
    if (key == "cost_sum")      return (sum == 0 ? "n/a" : "$" fmt(sum, 4))
    if (substr(key, 1, 2) == "j_") return jreport(key)
    return "n/a"
}

# Which questions a metric applies to is decided by the GROUND TRUTH category,
# never by what the judge chose to return. A judge that forgets to answer "n/a"
# must not be able to inflate a denominator.
function applies(q, key,   c) {
    c = qcat[q]
    if (key == "j_confab" || key == "j_decline") return (c == "unanswerable" || c == "unanswerable_trap")
    if (key == "j_contra")   return (c == "contradiction")
    if (key == "j_syn")      return (c == "synthesis")
    if (key == "j_overflag") return (c != "synthesis")
    # A compiled page can only be caught being wrong on a question where one is
    # known to be wrong. Both fixture families qualify: `poisoned_claim` (a page
    # that never matched its source) and `drift*` (a page whose source moved).
    if (key == "j_prop" || key == "j_caught")
        return (c == "poisoned_claim" || substr(c, 1, 5) == "drift")
    return 1
}

function jaccum(a, q, key,   v) {
    if (!applies(q, key)) return
    if (key == "j_corr")      { v = J[a,q,"judge_correctness"];      if (v != "") { JS += v + 0; JN++ } }
    if (key == "j_corr2")     { v = J[a,q,"judge_correctness"];      if (v != "") { JN++; if (v + 0 == 2) JH++ } }
    if (key == "j_cite")      { v = J[a,q,"judge_citation_support"]; if (v != "") { JS += v + 0; JN++ } }
    if (key == "j_cite2")     { v = J[a,q,"judge_citation_support"]; if (v != "") { JN++; if (v + 0 == 2) JH++ } }
    if (key == "j_unsourced") { v = J[a,q,"judge_unsourced_claims"]; if (v != "") { JS += v + 0; JN++ } }
    if (key == "j_confab")    { v = J[a,q,"judge_abstention"];       if (v != "") { JN++; if (v == "confabulated") JH++ } }
    if (key == "j_decline")   { v = J[a,q,"judge_abstention"];       if (v != "") { JN++; if (v == "correct_decline") JH++ } }
    if (key == "j_contra")    { v = J[a,q,"judge_contradiction"];    if (v != "") { JN++; if (v == "both_surfaced") JH++ } }
    if (key == "j_syn")       { v = J[a,q,"judge_synthesis_flag"];   if (v != "") { JN++; if (v == "flagged") JH++ } }
    if (key == "j_overflag")  { v = J[a,q,"judge_synthesis_flag"];   if (v != "") { JN++; if (v == "over_flagged") JH++ } }
    if (key == "j_prop")      { v = J[a,q,"judge_compiled_error"];   if (v != "") { JN++; if (v == "propagated") JH++ } }
    if (key == "j_caught")    { v = J[a,q,"judge_compiled_error"];   if (v != "") { JN++; if (v == "caught") JH++ } }
}

function jreport(key,   r) {
    if (JN == 0) { r = "n/a" }
    else if (key == "j_corr" || key == "j_cite") r = fmt(JS / JN, 2)
    else if (key == "j_unsourced")               r = JS ""
    else                                          r = JH " / " JN "  (" pct(JH, JN) ")"
    JS = 0; JN = 0; JH = 0
    return r
}
